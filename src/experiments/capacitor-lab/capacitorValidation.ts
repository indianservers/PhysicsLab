import { runBenchmarkCases } from "../shared/validation";
import {
  computeCapacitor,
  EPSILON_0,
  type CapacitorInput,
} from "./capacitorPhysics";
const base: CapacitorInput = {
  plateArea: 0.02,
  spacing: 0.002,
  dielectric: 1,
  voltage: 12,
  arrangement: "single",
  count: 1,
  connected: true,
};
export const capacitorBenchmarks = runBenchmarkCases<CapacitorInput>([
  {
    id: "geometry",
    name: "Parallel-plate capacitance",
    input: base,
    expected: (EPSILON_0 * 0.02) / 0.002,
    unit: "F",
    tolerance: 1e-20,
    actual: (v) => computeCapacitor(v).singleCapacitance,
  },
  {
    id: "charge",
    name: "Q equals CV",
    input: base,
    expected: ((EPSILON_0 * 0.02) / 0.002) * 12,
    unit: "C",
    tolerance: 1e-18,
    actual: (v) => computeCapacitor(v).charge,
  },
  {
    id: "energy",
    name: "U equals one-half CV squared",
    input: base,
    expected: ((0.5 * EPSILON_0 * 0.02) / 0.002) * 144,
    unit: "J",
    tolerance: 1e-18,
    actual: (v) => computeCapacitor(v).energy,
  },
  {
    id: "series",
    name: "Three equal capacitors in series",
    input: { ...base, arrangement: "series", count: 3 },
    expected: (EPSILON_0 * 0.02) / 0.002 / 3,
    unit: "F",
    tolerance: 1e-20,
    actual: (v) => computeCapacitor(v).equivalentCapacitance,
  },
  {
    id: "parallel",
    name: "Three equal capacitors in parallel",
    input: { ...base, arrangement: "parallel", count: 3 },
    expected: ((EPSILON_0 * 0.02) / 0.002) * 3,
    unit: "F",
    tolerance: 1e-20,
    actual: (v) => computeCapacitor(v).equivalentCapacitance,
  },
  {
    id: "series-field",
    name: "Each series capacitor sees one third of the supply voltage",
    input: { ...base, arrangement: "series", count: 3 },
    expected: 4 / 0.002,
    unit: "V/m",
    tolerance: 1e-12,
    actual: (v) => computeCapacitor(v).electricField,
  },
  {
    id: "series-field-energy-density",
    name: "Series gap energy density uses the per-capacitor field",
    input: { ...base, arrangement: "series", count: 3 },
    expected: 0.5 * EPSILON_0 * (4 / 0.002) ** 2,
    unit: "J/m³",
    tolerance: 1e-18,
    actual: (v) => computeCapacitor(v).energyDensity,
  },
  {
    id: "series-plate-force",
    name: "Force on each series capacitor uses its own voltage",
    input: { ...base, arrangement: "series", count: 3 },
    expected: 0.5 * EPSILON_0 * 0.02 * (4 / 0.002) ** 2,
    unit: "N",
    tolerance: 1e-20,
    actual: (v) => computeCapacitor(v).plateForce,
  },
]);
