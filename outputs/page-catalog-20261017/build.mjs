import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const out=new URL('./',import.meta.url);
const rows=JSON.parse(await fs.readFile(new URL('pages.json',out),'utf8'));
const wb=Workbook.create();const sh=wb.worksheets.add('All Pages');
sh.showGridLines=false;
sh.getRange('A2').values=[['Physics Simulator — page catalog']];
sh.getRange('A2').format.font={name:'Arial',size:16,bold:true,color:'#172554'};
sh.getRange('A3').values=[['589 URLs and linked views. Local source reviewed 17 Oct 2026. Deployment availability not checked.']];
sh.getRange('A4').values=[['Base URL: https://physics.aimersociety.com/ — filter by topic or page type to assign reviews.']];
const headers=['No.','Page / View','Topic / Category','Page Type','Description','Deployed Link','Route / View','Local Source','Notes'];
const values=rows.map((r,i)=>[i+1,r.title,r.topic,r.type,r.description,r.url,r.path,r.source,r.notes]);
sh.getRangeByIndexes(5,0,values.length+1,9).values=[headers,...values];
const end=rows.length+6;
sh.tables.add(`A6:I${end}`,true,'PageCatalog').style='TableStyleMedium2';
sh.getRange(`A6:I${end}`).format.font={name:'Arial',size:10,color:'#1F2937'};
sh.getRange('A6:I6').format={fill:'#172554',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},rowHeight:30,horizontalAlignment:'center',verticalAlignment:'center'};
sh.getRange(`A7:I${end}`).format={rowHeight:82,wrapText:true,verticalAlignment:'top'};
const widths=[7,34,30,22,88,70,48,45,35];widths.forEach((w,i)=>sh.getRangeByIndexes(5,i,rows.length+1,1).format.columnWidth=w);
sh.getRange(`F7:F${end}`).formulas=rows.map(r=>['=HYPERLINK("'+r.url.replaceAll('"','""')+'","'+r.url.replaceAll('"','""')+'")']);
sh.getRange(`F7:F${end}`).format.font={color:'#1D4ED8',underline:'single',name:'Arial',size:10};
sh.freezePanes.freezeRows(6);sh.freezePanes.freezeColumns(2);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'All Pages!A6:F9',include:'values,formulas',tableMaxCols:6,tableMaxRows:4})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#N/A',options:{useRegex:true,maxResults:10},summary:'Formula errors'})).ndjson);
const preview=await wb.render({sheetName:'All Pages',range:'A6:E11',scale:1,format:'png'});
await fs.writeFile(new URL('preview.png',out),new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(fileURLToPath(new URL('physics_pages_catalog.xlsx',out)));
console.log('Exported '+rows.length+' unique URLs.');
